-- Conserva datos; no carga seeds ni inventa stock o historial.
-- Puede repetirse. Un error revierte todos los cambios de esta ejecucion.
-- Mantener sincronizado con las nuevas migraciones.

BEGIN;
SET LOCAL search_path TO public;

DO $$
BEGIN
  IF to_regclass('public.maquinas_productos') IS NOT NULL
    AND to_regclass('public.maquina_productos') IS NULL THEN
    RAISE EXCEPTION 'Existe maquinas_productos (plural). Revisar ese esquema antes de continuar; la aplicacion usa maquina_productos.';
  END IF;
END;
$$;

CREATE TABLE IF NOT EXISTS proveedores (
  id_proveedor integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre text NOT NULL UNIQUE,
  estado boolean NOT NULL DEFAULT true,
  fecha_creacion timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS maquinas (
  id_maquina integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo text NOT NULL UNIQUE,
  nombre text NOT NULL,
  descripcion text NOT NULL DEFAULT '',
  ubicacion text NOT NULL,
  estado text NOT NULL DEFAULT 'ACTIVA' CHECK (estado IN ('ACTIVA', 'INACTIVA', 'MANTENCION')),
  fecha_creacion timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS productos (
  id_producto integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre text NOT NULL UNIQUE,
  precio_venta numeric(12, 2) NOT NULL CHECK (precio_venta >= 0),
  costo_compra numeric(12, 2) NOT NULL DEFAULT 0 CHECK (costo_compra >= 0),
  estado boolean NOT NULL DEFAULT true,
  fecha_creacion timestamptz NOT NULL DEFAULT now(),
  id_proveedor integer REFERENCES proveedores(id_proveedor) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS maquina_productos (
  id_maquina_producto integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_maquina integer NOT NULL REFERENCES maquinas(id_maquina) ON DELETE CASCADE,
  id_producto integer NOT NULL REFERENCES productos(id_producto) ON DELETE RESTRICT,
  capacidad_maxima integer NOT NULL CHECK (capacidad_maxima >= 0),
  stock_actual integer NOT NULL CHECK (stock_actual BETWEEN 0 AND capacidad_maxima),
  precio_venta_actual numeric(12, 2) NOT NULL CHECK (precio_venta_actual >= 0),
  estado boolean NOT NULL DEFAULT true,
  UNIQUE (id_maquina, id_producto)
);

CREATE TABLE IF NOT EXISTS usuarios (
  id_usuario integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre text NOT NULL,
  apellido text NOT NULL,
  email text NOT NULL UNIQUE,
  password_hash text NOT NULL,
  rol text NOT NULL CHECK (rol IN ('ADMIN', 'REPONEDOR')),
  estado boolean NOT NULL DEFAULT true,
  fecha_creacion timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS reposiciones (
  id_reposicion integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_maquina integer NOT NULL REFERENCES maquinas(id_maquina),
  dinero_retirado numeric(12, 2) NOT NULL CHECK (dinero_retirado >= 0),
  observacion text,
  venta_esperada numeric(12, 2) NOT NULL CHECK (venta_esperada >= 0),
  diferencia_dinero numeric(12, 2) NOT NULL,
  fecha_creacion timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS reposicion_detalles (
  id_reposicion_detalle integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_reposicion integer NOT NULL REFERENCES reposiciones(id_reposicion) ON DELETE CASCADE,
  id_maquina_producto integer NOT NULL REFERENCES maquina_productos(id_maquina_producto),
  stock_sistema integer NOT NULL CHECK (stock_sistema >= 0),
  stock_encontrado integer NOT NULL CHECK (stock_encontrado >= 0),
  cantidad_vendida integer NOT NULL CHECK (cantidad_vendida >= 0),
  cantidad_repuesta integer NOT NULL CHECK (cantidad_repuesta >= 0),
  cantidad_retirada integer NOT NULL CHECK (cantidad_retirada >= 0),
  stock_final integer NOT NULL CHECK (stock_final >= 0),
  precio_venta_actual numeric(12, 2) NOT NULL CHECK (precio_venta_actual >= 0),
  venta_esperada numeric(12, 2) NOT NULL CHECK (venta_esperada >= 0)
);

CREATE INDEX IF NOT EXISTS reposiciones_id_maquina_fecha_idx ON reposiciones (id_maquina, fecha_creacion DESC);
CREATE INDEX IF NOT EXISTS reposicion_detalles_id_reposicion_idx ON reposicion_detalles (id_reposicion);

CREATE TABLE IF NOT EXISTS bodega_productos (
  id_producto integer PRIMARY KEY REFERENCES productos(id_producto),
  stock_actual integer NOT NULL DEFAULT 0 CHECK (stock_actual >= 0)
);

CREATE TABLE IF NOT EXISTS bodega_movimientos (
  id_movimiento integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_producto integer NOT NULL REFERENCES productos(id_producto),
  tipo text NOT NULL CHECK (tipo IN ('ENTRADA', 'SALIDA')),
  cantidad integer NOT NULL CHECK (cantidad > 0),
  stock_final integer NOT NULL CHECK (stock_final >= 0),
  observacion text,
  fecha_creacion timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS bodega_movimientos_producto_idx ON bodega_movimientos (id_producto);

CREATE TABLE IF NOT EXISTS camionetas (
  id_camioneta integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patente text NOT NULL UNIQUE CHECK (patente <> '' AND patente = upper(btrim(patente))),
  nombre text NOT NULL CHECK (btrim(nombre) <> ''),
  id_repartidor integer NOT NULL UNIQUE REFERENCES usuarios(id_usuario),
  estado boolean NOT NULL DEFAULT true,
  fecha_creacion timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS camioneta_productos (
  id_camioneta integer NOT NULL REFERENCES camionetas(id_camioneta),
  id_producto integer NOT NULL REFERENCES productos(id_producto),
  stock_actual integer NOT NULL DEFAULT 0 CHECK (stock_actual >= 0),
  PRIMARY KEY (id_camioneta, id_producto)
);

CREATE TABLE IF NOT EXISTS camioneta_movimientos (
  id_movimiento integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_camioneta integer NOT NULL REFERENCES camionetas(id_camioneta),
  id_producto integer NOT NULL REFERENCES productos(id_producto),
  id_bodeguero integer REFERENCES usuarios(id_usuario),
  id_repartidor integer NOT NULL REFERENCES usuarios(id_usuario),
  id_movimiento_bodega integer UNIQUE REFERENCES bodega_movimientos(id_movimiento),
  cantidad integer NOT NULL CHECK (cantidad > 0),
  stock_final integer NOT NULL CHECK (stock_final >= 0),
  observacion text,
  fecha_creacion timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS camioneta_movimientos_camioneta_idx ON camioneta_movimientos (id_camioneta, id_movimiento DESC);

CREATE TABLE IF NOT EXISTS conteos (
  id_conteo integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_camioneta integer REFERENCES camionetas(id_camioneta) ON DELETE RESTRICT,
  id_producto integer NOT NULL REFERENCES productos(id_producto) ON DELETE RESTRICT,
  id_responsable integer NOT NULL REFERENCES usuarios(id_usuario) ON DELETE RESTRICT,
  stock_esperado integer NOT NULL CHECK (stock_esperado >= 0),
  stock_fisico integer NOT NULL CHECK (stock_fisico >= 0),
  diferencia integer GENERATED ALWAYS AS (stock_fisico - stock_esperado) STORED,
  observacion text,
  fecha_creacion timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS conteos_ubicacion_idx ON conteos (id_camioneta, id_conteo DESC);

-- Completa las tablas antiguas sin recrearlas (migraciones 006, 008 y 009).
ALTER TABLE reposiciones
  ADD COLUMN IF NOT EXISTS id_camioneta integer REFERENCES camionetas(id_camioneta),
  ADD COLUMN IF NOT EXISTS id_repartidor integer REFERENCES usuarios(id_usuario);

ALTER TABLE camioneta_movimientos
  ALTER COLUMN id_bodeguero DROP NOT NULL,
  ALTER COLUMN id_movimiento_bodega DROP NOT NULL,
  ADD COLUMN IF NOT EXISTS tipo text NOT NULL DEFAULT 'ENTRADA' CHECK (tipo IN ('ENTRADA', 'SALIDA')),
  ADD COLUMN IF NOT EXISTS id_reposicion integer REFERENCES reposiciones(id_reposicion),
  ADD COLUMN IF NOT EXISTS id_maquina integer REFERENCES maquinas(id_maquina);

CREATE UNIQUE INDEX IF NOT EXISTS camioneta_movimientos_reposicion_producto_idx
  ON camioneta_movimientos (id_reposicion, id_producto) WHERE id_reposicion IS NOT NULL;

ALTER TABLE maquinas
  ADD COLUMN IF NOT EXISTS modelo text NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS sistemas_pago text[] NOT NULL DEFAULT '{}'::text[];

CREATE TABLE IF NOT EXISTS reposicion_operaciones (
  id_operacion uuid PRIMARY KEY,
  solicitud jsonb NOT NULL,
  respuesta jsonb
);

ALTER TABLE maquina_productos ADD COLUMN IF NOT EXISTS version integer NOT NULL DEFAULT 1;

CREATE OR REPLACE FUNCTION incrementar_version_inventario() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  NEW.version := OLD.version + 1;
  RETURN NEW;
END;
$$;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgrelid = 'maquina_productos'::regclass AND tgname = 'maquina_productos_version') THEN
    CREATE TRIGGER maquina_productos_version
      BEFORE UPDATE ON maquina_productos
      FOR EACH ROW EXECUTE FUNCTION incrementar_version_inventario();
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'reposiciones'::regclass AND conname = 'reposiciones_asignacion_check') THEN
    ALTER TABLE reposiciones ADD CONSTRAINT reposiciones_asignacion_check
      CHECK ((id_camioneta IS NULL) = (id_repartidor IS NULL));
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'camioneta_movimientos'::regclass AND conname = 'camioneta_movimientos_origen_check') THEN
    ALTER TABLE camioneta_movimientos ADD CONSTRAINT camioneta_movimientos_origen_check CHECK (
      (tipo = 'ENTRADA' AND id_bodeguero IS NOT NULL AND id_movimiento_bodega IS NOT NULL
        AND id_reposicion IS NULL AND id_maquina IS NULL)
      OR
      (tipo = 'SALIDA' AND id_bodeguero IS NULL AND id_movimiento_bodega IS NULL
        AND id_reposicion IS NOT NULL AND id_maquina IS NOT NULL)
    );
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'maquinas'::regclass AND conname = 'maquinas_modelo_check') THEN
    ALTER TABLE maquinas ADD CONSTRAINT maquinas_modelo_check CHECK (modelo = btrim(modelo));
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'maquinas'::regclass AND conname = 'maquinas_sistemas_pago_check') THEN
    ALTER TABLE maquinas ADD CONSTRAINT maquinas_sistemas_pago_check CHECK (
      CASE
        WHEN cardinality(sistemas_pago) = 0 THEN true
        WHEN array_ndims(sistemas_pago) = 1 THEN
          sistemas_pago <@ ARRAY['MONEDA', 'BILLETE', 'TARJETA']::text[]
          AND array_position(sistemas_pago, NULL) IS NULL
          AND cardinality(sistemas_pago) =
            (CASE WHEN 'MONEDA' = ANY(sistemas_pago) THEN 1 ELSE 0 END)
            + (CASE WHEN 'BILLETE' = ANY(sistemas_pago) THEN 1 ELSE 0 END)
            + (CASE WHEN 'TARJETA' = ANY(sistemas_pago) THEN 1 ELSE 0 END)
        ELSE false
      END
    );
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'productos'::regclass AND conname = 'productos_importes_sin_nan') THEN
    ALTER TABLE productos ADD CONSTRAINT productos_importes_sin_nan
      CHECK (precio_venta <> 'NaN'::numeric AND costo_compra <> 'NaN'::numeric);
  END IF;
END;
$$;

